def stiffness_points(results, phase, runs):
    """Reconstruct the prediction from contact parameters, without using measured force."""
    points = []
    for run in runs:
        path = results / phase / run["run_id"] / "equilibrium_contacts.csv"
        with path.open() as f:
            for contact in csv.DictReader(f):
                delta, force = float(contact["penetration"]), float(contact["f_n"])
                if delta <= 1e-8 or force <= 1e-5:
                    continue
                k, damping = physical_coefficients(
                    [float(contact[f"solref_{i}"]) for i in range(2)],
                    [float(contact[f"solimp_{i}"]) for i in range(5)],
                    float(contact["Lambda_approx"]),
                    run["timestep"],
                )
                points.append(
                    dict(
                        run_id=run["run_id"],
                        geometry=run["geometry"],
                        mode=run["mode"],
                        mapping_policy=run.get("mapping_policy", "frozen"),
                        mass_scale=run["mass_scale"],
                        sample_id=int(contact["sample_id"]),
                        penetration=delta,
                        force=force,
                        measured_stiffness=force / delta,
                        predicted_stiffness=k,
                        target_stiffness=float(contact["k_i"]),
                        predicted_damping=damping,
                        prediction_relative_error=force / delta / k - 1,
                        target_relative_error=force / delta / float(contact["k_i"]) - 1,
                    )
                )
    return points


