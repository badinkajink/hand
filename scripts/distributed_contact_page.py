def convert_spec():
    with ZipFile(SOURCE) as z:
        body = ET.fromstring(z.read("word/document.xml")).find("w:body", NS)
    parts, paragraphs = [], []

    def text_of(e):
        return "".join(e.itertext())

    for index, e in enumerate(body):
        if e.tag == W + "tbl":
            rows = []
            for tr in e.findall("w:tr", NS):
                rows.append(
                    [
                        "\n".join(text_of(p) for p in tc.findall("w:p", NS))
                        for tc in tr.findall("w:tc", NS)
                    ]
                )
            if rows:
                parts.append(table(rows[0], rows[1:]))
                paragraphs.extend(value for row in rows for value in row)
        elif e.tag == W + "p":
            text = text_of(e)
            if not text.strip():
                continue
            paragraphs.append(text)
            # Preserve run emphasis and all supplied words, including callout labels.
            spans = []
            for run in e.findall(".//w:r", NS):
                value = "".join((t.text or "") for t in run.findall("w:t", NS))
                safe = html.escape(value)
                if run.find("w:rPr/w:b", NS) is not None:
                    safe = "<strong>" + safe + "</strong>"
                spans.append(safe)
                if run.find("w:br", NS) is not None:
                    spans.append("<br>")
            rendered = "".join(spans)
            if re.match(r"^\d+\.\d+ ", text) or text.startswith("Phase "):
                tag = "h3"
            elif (
                re.match(r"^\d+\. ", text)
                and len(text) < 85
                or text
                in (
                    "Start here: first four actions",
                    "Recommended stopping point for the first Codex session",
                )
            ):
                tag = "h2"
            else:
                tag = "p"
            parts.append(f"<{tag}>{rendered}</{tag}>")
    note = (
        "Faithful conversion of the supplied DOCX; its hypotheses and baseline claims are preserved here. "
        'The <a href="20261004-distributed_contact.html">measured follow-up</a> qualifies the static spring interpretation. '
        '<a href="' + SOURCE.name + '">Download original DOCX</a>.'
    )
    content = '<section><div class="col">' + "".join(parts) + "</div></section>"
    page = frame(
        "Distributed fingertip contact: experiment specification",
        note,
        content,
        "Source document, preserved separately from measured findings",
    )
    (DOC / "20261004-distributed_contact_spec.html").write_text(retro_style.apply(page))  # plain page style (owner, 2026-10-09)
    # Validate every paragraph/cell text survives conversion, independent of formatting.
    from html.parser import HTMLParser

    class Text(HTMLParser):
        def __init__(self):
            super().__init__()
            self.values = []

        def handle_data(self, value):
            self.values.append(value)

    parsed = Text()
    parsed.feed(page)
    combined = re.sub(r"\s+", "", "".join(parsed.values))
    assert all(re.sub(r"\s+", "", p) in combined for p in paragraphs)
    return len(paragraphs)


def save_figure(fig, name, caption):
    figures = DOC / "figures"
    figures.mkdir(exist_ok=True)
    fig.savefig(figures / f"{name}.svg", bbox_inches="tight")
    fig.savefig(figures / f"{name}.png", dpi=180, bbox_inches="tight")
    plt.close(fig)
    # Embed SVG in the page so the report remains portable; export standalone files as well.
    encoded = base64.b64encode((figures / f"{name}.svg").read_bytes()).decode()
    return (
        f'<figure><img src="data:image/svg+xml;base64,{encoded}" alt="{html.escape(caption)}"><figcaption>{caption} '
        f'<a href="figures/{name}.svg">SVG</a> · <a href="figures/{name}.png">PNG</a></figcaption></figure>'
    )


def choose(rows, **where):
    return [
        r
        for r in rows
        if all(r.get(k) == v for k, v in where.items()) and r["status"] == "complete"
    ]


