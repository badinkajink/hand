#!/usr/bin/env python3
"""The AmazingHand's two-rod differential at the finger base, against the SR2 bench trials and a bevel differential.

Pollen Robotics' AmazingHand (github.com/pollen-robotics/AmazingHand, Apache-2.0) drives each finger's universal joint
with two servos in the palm. Each servo horn turns a ball-jointed rod whose upper end is fixed to the proximal link;
pushing both rods flexes the finger, pushing one and pulling the other abducts it. The distal link is coupled to the
proximal one by a four-bar from the gimbal. This script takes the geometry of the right hand's first finger from the
project's MuJoCo model (Demo/AHSimulation/AHSimulation/AH_Right/mjcf, generated by onshape-to-robot) and solves the
rods in closed form over abduction and flexion.

extract  MJCF [SHA]   read the geometry at the model's key "zero", check the closed-form solution against MuJoCo's
                      own closure (servo pairs driven by the model's position actuators, gravity off), and write
                      data/20261119-amazinghand_geometry.json
analyse              the reachable joint angles with each horn within +-90 deg of its zero (the model's joint range and
                      the demo's command range), joint torques at the servo limit, joint error per rod play, the share
                      of the SR2 bench trials' yaw and MCP angles inside the reachable region, the same for horns 1.5x
                      and 2x longer, and the figure; writes data/20261119-amazinghand.json

Angles: abduction a is the turn about the palm normal, flexion f the turn about the gimbal's lateral axis, positive
toward the palm, zero with the line from the joint centre to the PIP axis along the palm. Lengths in mm.
"""
