HORN_LIMIT = 90.0  # deg; the model's motor joint range and the demo's commands (CloseHand 90/-90, SpreadHand 4/90)
SCALES = (1.0, 1.5, 2.0, 3.0)  # horn radius over the AmazingHand's
TORQUE_FLOOR = 1.0  # joint torque per servo limit that each joint must reach: one servo per joint gives 1
STEP = 0.5  # deg, grid of abduction and flexion
A_GRID = np.arange(-90.0, 90.0 + 1e-9, STEP)
F_GRID = np.arange(-90.0, 150.0 + 1e-9, STEP)


def cmd_extract(mjcf, sha):
    import mujoco as mj
    from scipy.spatial.transform import Rotation

    m = mj.MjModel.from_xml_path(mjcf)
    d = mj.MjData(m)
    mj.mj_resetDataKeyframe(m, d, m.key("zero").id)
    mj.mj_forward(m, d)
    site = lambda n: d.site_xpos[m.site(n).id].copy()  # noqa: E731
    anchor = lambda n: d.xanchor[m.joint(n).id].copy()  # noqa: E731
    axis = lambda n: d.xaxis[m.joint(n).id].copy()  # noqa: E731
    palmar = np.array([1.0, 0.0, 0.0])  # the curled fingers and the thumb's base lie toward +x
    e_a = unit(site("closing_1 (1)_2_z") - site("closing_1 (1)_2"))
    e_a *= np.sign(e_a @ palmar)
    p_a = site("closing_1 (1)_2")
    p_f, e_f = anchor("passive2 (1)"), unit(axis("passive2 (1)"))
    pip = anchor("passive4 (1)")
    if (np.cross(e_f, pip - p_f) @ palmar) < 0:
        e_f = -e_f  # a positive turn about e_f moves the finger toward the palm
    # joint centre: the closest points of the two axes
    w0 = p_a - p_f
    b = e_a @ e_f
    s = (b * (e_f @ w0) - (e_a @ w0)) / (1 - b * b)
    t = ((e_f @ w0) - b * (e_a @ w0)) / (1 - b * b)
    c_a, c_f = p_a + s * e_a, p_f + t * e_f
    O = (c_a + c_f) / 2
    rods = []
    for k, (motor, ball_low, ball_high) in enumerate((("finger1_motor1", "passive_ball1", ("joint", "passive_ball2")),
                                                      ("finger1_motor2", "passive_ball3", ("site", "closing_ball1_2")))):
        h_anchor, h_axis = anchor(motor), unit(axis(motor))
        th0 = float(d.qpos[m.jnt_qposadr[m.joint(motor).id]])
        B = anchor(ball_low)
        C = h_anchor + h_axis * ((B - h_anchor) @ h_axis)
        u = rot_axis_angle(h_axis, -th0) @ (B - C)
        r = float(np.linalg.norm(u))
        A = anchor(ball_high[1]) if ball_high[0] == "joint" else site(ball_high[1])
        rng = np.degrees(m.jnt_range[m.joint(motor).id]).round(3).tolist()
        rods.append({"motor": motor, "horn_axis": h_axis.tolist(), "horn_centre_mm": (1e3 * C).tolist(),
                     "horn_zero_dir": unit(u).tolist(), "horn_radius_mm": 1e3 * r, "horn_angle_at_key_deg": math.degrees(th0),
                     "attach_mm": (1e3 * A).tolist(), "rod_mm": 1e3 * float(np.linalg.norm(A - B)), "motor_range_deg": rng})
    pip_dir = pip - O
    f0 = math.degrees(math.atan2(pip_dir @ palmar, pip_dir @ np.cross(palmar, e_f)))
    geom = {"source": UPSTREAM, "commit": sha, "model": "Demo/AHSimulation/AHSimulation/AH_Right/mjcf/scene.xml, finger 1",
            "joint_centre_mm": (1e3 * O).tolist(), "axis_gap_mm": 1e3 * float(np.linalg.norm(c_a - c_f)),
            "abduction_axis": e_a.tolist(), "flexion_axis": e_f.tolist(), "pip_axis_point_mm": (1e3 * pip).tolist(),
            "flexion_at_key_deg": f0, "palmar": palmar.tolist(), "rods": rods}
    # check the closed form against MuJoCo's closure: drive the two motors, let the passive joints settle
    G = load_geom(geom)
    m.opt.gravity[:] = 0.0  # the closed form is static and massless
    act = [m.actuator(n).id for n in ("finger1_motor1", "finger1_motor2")]
    prox = m.body("rotule_ball").id
    R_key = d.xmat[prox].reshape(3, 3).copy()
    F = np.column_stack([e_a, e_f, np.cross(e_a, e_f)])
    rows = []
    for th in ((0, 0), (40, -40), (-30, 30), (70, -70), (30, 10), (-10, -50), (60, 20), (-60, 0), (85, -60), (-45, 80)):
        mj.mj_resetDataKeyframe(m, d, m.key("zero").id)
        d.ctrl[act] = np.radians(th)
        for _ in range(4000):
            mj.mj_step(m, d)
        q_sim = np.degrees([d.qpos[m.jnt_qposadr[m.joint(n).id]] for n in ("finger1_motor1", "finger1_motor2")])
        gap = max(float(np.linalg.norm(site(a_) - site(b_))) for a_, b_ in (
            ("closing_1 (1)_1", "closing_1 (1)_2"), ("closing_3 (1)_1", "closing_3 (1)_2"),
            ("closing_ball1_1", "closing_ball1_2")))
        dR = F.T @ (d.xmat[prox].reshape(3, 3) @ R_key.T) @ F
        a, f, z = Rotation.from_matrix(dR).as_euler("XYZ")
        th_ik, ok = horn_angles(G, np.array([a]), np.array([f]))
        rows.append({"command_deg": list(th), "motor_sim_deg": q_sim.round(3).tolist(),
                     "abduction_deg": round(math.degrees(a), 3), "flexion_deg": round(math.degrees(f) + f0, 3),
                     "residual_turn_deg": round(math.degrees(z), 4),
                     "motor_closed_form_deg": np.degrees(th_ik[:, 0]).round(3).tolist(),
                     "closed_form_error_deg": round(float(np.abs(np.degrees(th_ik[:, 0]) - q_sim).max()), 4),
                     "closure_gap_mm": round(1e3 * gap, 4)})
    geom["closure_check"] = {"settle_steps": 4000, "timestep_s": float(m.opt.timestep), "rows": rows,
                             "max_error_deg": max(r["closed_form_error_deg"] for r in rows)}
    GEOM.parent.mkdir(parents=True, exist_ok=True)
    GEOM.write_text(json.dumps(geom, indent=1))
    return {k: geom[k] for k in ("joint_centre_mm", "axis_gap_mm", "flexion_at_key_deg")} | {
        "rods": [{k: r[k] for k in ("horn_radius_mm", "rod_mm", "motor_range_deg")} for r in rods],
        "closure_max_error_deg": geom["closure_check"]["max_error_deg"]}


def load_geom(geom=None, scale=1.0):
    """Arrays in mm. scale multiplies the horn radius; the horn's centre moves so the ball and the rod keep their key
    positions."""
    g = geom or json.loads(GEOM.read_text())
    G = {"O": np.array(g["joint_centre_mm"]), "e_a": np.array(g["abduction_axis"]), "e_f": np.array(g["flexion_axis"]),
         "f0": g["flexion_at_key_deg"], "rods": []}
    for r in g["rods"]:
        ax, u, th0 = np.array(r["horn_axis"]), np.array(r["horn_zero_dir"]), math.radians(r["horn_angle_at_key_deg"])
        C, A = np.array(r["horn_centre_mm"]), np.array(r["attach_mm"])
        u_key = rot_axis_angle(ax, th0) @ u
        B0 = C + r["horn_radius_mm"] * u_key
        rad = r["horn_radius_mm"] * scale
        C = B0 - rad * u_key
        rod = {"axis": ax, "u": u, "v": np.cross(ax, u), "C": C, "A": A, "r": rad, "L": float(np.linalg.norm(A - B0)),
               "th0": th0}
        w = A - C
        p_, q_ = w @ rod["u"], w @ rod["v"]
        k = (w @ w + rad ** 2 - rod["L"] ** 2) / (2 * rad)
        acos = math.acos(float(np.clip(k / math.hypot(p_, q_), -1.0, 1.0)))
        rod["branch"] = min((1.0, -1.0), key=lambda b: abs(float(wrap(math.atan2(q_, p_) + b * acos - th0))))
        G["rods"].append(rod)
    return G


def pose(G, a, f):
    """Rotation of the proximal link from the key pose: abduction a (rad) about the palm normal after flexion f (rad,
    from the key) about the gimbal's lateral axis. Batched over a and f."""
    return rot_axis_angle(np.broadcast_to(G["e_a"], a.shape + (3,)), a) @ rot_axis_angle(
        np.broadcast_to(G["e_f"], f.shape + (3,)), f)


def horn_angles(G, a, f):
    """Horn angles (rad), shape (2, ...), on the branch through the key pose, and whether each rod closes."""
    R = pose(G, a, f)
    th, ok = [], []
    for rod in G["rods"]:
        A = G["O"] + (R @ (rod["A"] - G["O"]))
        w = A - rod["C"]
        p, q = w @ rod["u"], w @ rod["v"]
        k = ((w * w).sum(-1) + rod["r"] ** 2 - rod["L"] ** 2) / (2 * rod["r"])
        rho = np.hypot(p, q)
        good = np.abs(k) <= rho
        acos = np.arccos(np.clip(k / np.where(rho > 0, rho, 1.0), -1.0, 1.0))
        phi = np.arctan2(q, p)
        branch = rod["branch"]
        th.append(wrap(phi + branch * acos))
        ok.append(good)
    return np.array(th), np.array(ok)


def wrap(x):
    return (np.asarray(x) + np.pi) % (2 * np.pi) - np.pi


@np.errstate(divide="ignore", invalid="ignore")
def statics(G, a, f, th):
    """Per pose: H (2 x 2, joint torque [abduction, flexion] per servo torque) and the horn transmission t.n."""
    R = pose(G, a, f)
    e_f = R @ G["e_f"]  # the flexion axis turns with the abduction only; R e_f = Ra Rf e_f = Ra e_f
    cols, tn = [], []
    for i, rod in enumerate(G["rods"]):
        A = G["O"] + (R @ (rod["A"] - G["O"]))
        B = rod["C"] + rod["r"] * (np.cos(th[i])[..., None] * rod["u"] + np.sin(th[i])[..., None] * rod["v"])
        n = (A - B) / np.linalg.norm(A - B, axis=-1, keepdims=True)
        t = -np.sin(th[i])[..., None] * rod["u"] + np.cos(th[i])[..., None] * rod["v"]
        c = (t * n).sum(-1)
        tau = np.cross(A - G["O"], n)  # mm; moment about O of a unit force on the link along n = (A - B) / |A - B|
        # a servo torque T moves the ball along t, so the rod pushes the link along n with F = T / (r c)
        cols.append(np.stack([(tau * G["e_a"]).sum(-1), (tau * e_f).sum(-1)], -1) / (rod["r"] * c[..., None]))
        tn.append(c)
    return np.stack(cols, -1), np.array(tn)


def axis_capacity(H, j):
    """Largest torque about joint j (0 abduction, 1 flexion) with the other joint's torque zero and |T_i| <= 1."""
    o = 1 - j
    best = np.zeros(H.shape[:-2])
    for fixed in (0, 1):
        free = 1 - fixed
        for sgn in (1.0, -1.0):
            # T_fixed = sgn, choose T_free so the other joint's torque is zero
            with np.errstate(divide="ignore", invalid="ignore"):
                T_free = -H[..., o, fixed] * sgn / H[..., o, free]
            okk = np.abs(T_free) <= 1.0
            val = np.abs(H[..., j, fixed] * sgn + H[..., j, free] * np.where(okk, T_free, 0.0))
            best = np.maximum(best, np.where(okk, val, 0.0))
    return best


def region(G):
    """The joint angles the finger reaches: both rods close, both horns within HORN_LIMIT of their zero, and each joint
    can take at least one servo's torque (TORQUE_FLOOR), in the connected piece that holds the key pose."""
    from scipy import ndimage

    a, f = np.meshgrid(np.radians(A_GRID), np.radians(F_GRID - G["f0"]), indexing="ij")
    th, ok = horn_angles(G, a, f)
    H, tn = statics(G, a, f, th)
    cap_f, cap_a = axis_capacity(H, 1), axis_capacity(H, 0)
    inside = ok.all(0) & (np.abs(np.degrees(th)) <= HORN_LIMIT + 1e-9).all(0) & (cap_f >= TORQUE_FLOOR) & (
        cap_a >= TORQUE_FLOOR)
    lab, _n = ndimage.label(inside)
    key = (int(np.argmin(np.abs(A_GRID))), int(np.argmin(np.abs(F_GRID - G["f0"]))))
    inside = lab == lab[key] if lab[key] else np.zeros_like(inside)
    return a, f, th, inside, H, tn, cap_f, cap_a


def extent(inside):
    """Largest flexion span at one abduction and largest abduction span at one flexion, in deg."""
    f_span = max((F_GRID[c].max() - F_GRID[c].min() for c in inside if c.any()), default=0.0)
    a_span = max((A_GRID[c].max() - A_GRID[c].min() for c in inside.T if c.any()), default=0.0)
    return float(f_span), float(a_span)


def coverage(inside, pts):
    """Share of the points (yaw, MCP in deg) inside the region when the region is shifted by (da, df) as a whole, at
    the best shift. A shift turns the whole finger module, servos included, about the palm normal or the lateral axis."""
    ia = np.round((pts[:, 0] - A_GRID[0]) / STEP).astype(int)
    jf = np.round((pts[:, 1] - F_GRID[0]) / STEP).astype(int)
    best = (0.0, 0.0, 0.0)
    for da in np.arange(-60.0, 60.0 + 1e-9, 1.0):
        for df in np.arange(-60.0, 60.0 + 1e-9, 1.0):
            i = ia - int(round(da / STEP))
            j = jf - int(round(df / STEP))
            okk = (i >= 0) & (i < inside.shape[0]) & (j >= 0) & (j < inside.shape[1])
            share = float(inside[i[okk], j[okk]].sum()) / len(pts)
            if share > best[0]:
                best = (share, float(da), float(df))
    return best


def cmd_analyse():
    import cad_v4_layouts as L

    geom = json.loads(GEOM.read_text())
    rows = L.load_trials()
    pts = {f: np.array([r["q"][f][:2] for r in rows]) for f in L.FINGERS}
    driver = np.array([[y, mcp] for y in np.arange(-85, 85.1, 1.0) for mcp in np.arange(-15, 92.1, 1.0)])
    res = {"script": "scripts/cad/amazinghand_differential.py", "command": "analyse", "source": geom["source"],
           "commit": geom["commit"], "horn_limit_deg": HORN_LIMIT, "grid_step_deg": STEP,
           "trial_periods_per_finger": len(rows), "torque_floor_per_servo_limit": TORQUE_FLOOR,
           "bevel_diamond_scs0009_1to1_area_deg2": 2 * 150.0 ** 2, "driver_rectangle_area_deg2": 170.0 * 107.0,
           "geometry": {
               "horn_radius_mm": [round(r["horn_radius_mm"], 3) for r in geom["rods"]],
               "rod_mm": [round(r["rod_mm"], 3) for r in geom["rods"]],
               "flexion_at_key_deg": round(geom["flexion_at_key_deg"], 2),
               "closure_check_max_error_deg": geom["closure_check"]["max_error_deg"]}, "scales": {}}
    G1 = load_geom()
    O = G1["O"]
    pal = np.array(geom["palmar"])
    lat = np.cross(pal, G1["e_f"])  # along the finger at zero flexion... (palm plane, perpendicular to e_f)
    res["geometry"]["attach_offsets_mm"] = [
        {"palmar": round(float((r["A"] - O) @ pal), 2), "lateral": round(float((r["A"] - O) @ G1["e_f"]), 2),
         "along_finger": round(float((r["A"] - O) @ lat), 2)} for r in G1["rods"]]
    res["geometry"]["horn_below_joint_mm"] = [round(float((O - r["C"]) @ lat), 2) for r in G1["rods"]]
    maps = {}
    for s in SCALES:
        G = load_geom(scale=s)
        a, f, th, inside, H, tn, cap_f, cap_a = region(G)
        f_span, a_span = extent(inside)
        cov = {fn: coverage(inside, pts[fn]) for fn in L.FINGERS}
        cov_driver = coverage(inside, driver)
        # torque at the key pose (centre of the region) and its median over the region
        ik = np.unravel_index(np.argmin(np.abs(a) + np.abs(f)), a.shape)
        # joint angle error per 0.1 mm of play in one rod, and per 1 deg of play at one horn, at the key pose
        Hk = H[ik]
        M_T = (Hk * np.array([r["r"] for r in G["rods"]])[None, :] * tn[(slice(None),) + ik][None, :]).T  # mm
        per_mm = np.degrees(np.abs(np.linalg.inv(M_T))) * 0.1
        per_deg = np.abs(np.linalg.inv(Hk.T))
        flex_at_zero_abd = F_GRID[inside[np.argmin(np.abs(A_GRID))]]
        abd_at_key = A_GRID[inside[:, np.argmin(np.abs(F_GRID - G["f0"]))]]
        span = lambda x: [float(x.min()), float(x.max())] if x.size else None  # noqa: E731
        pct = lambda x: [round(float(np.percentile(x[inside], q)), 3) for q in (10, 50)] if inside.any() else None  # noqa: E731
        res["scales"][f"{s:g}"] = {
            "horn_radius_mm": [round(r["r"], 3) for r in G["rods"]], "rod_mm": [round(r["L"], 3) for r in G["rods"]],
            "reachable_area_deg2": float(inside.sum() * STEP * STEP),
            "largest_flexion_span_deg": f_span, "largest_abduction_span_deg": a_span,
            "flexion_range_at_zero_abduction_deg": span(flex_at_zero_abd),
            "abduction_range_at_key_flexion_deg": span(abd_at_key),
            "trial_share_inside_best_shift": {fn: {"share": round(c[0], 4), "shift_yaw_deg": c[1], "shift_mcp_deg": c[2]}
                                              for fn, c in cov.items()},
            "driver_rectangle_share_inside_best_shift": round(cov_driver[0], 4),
            "flexion_torque_per_servo_limit_at_key": round(float(cap_f[ik]), 3),
            "abduction_torque_per_servo_limit_at_key": round(float(cap_a[ik]), 3),
            "flexion_torque_per_servo_limit_p10_p50_over_region": pct(cap_f),
            "abduction_torque_per_servo_limit_p10_p50_over_region": pct(cap_a),
            "servo_deg_per_joint_deg_at_key": {"pure_flexion": round(float(np.abs(Hk[1]).mean()), 3),
                                               "pure_abduction": round(float(np.abs(Hk[0]).mean()), 3)},
            "joint_error_per_0.1mm_rod_play_at_key_deg": {"abduction": round(float(per_mm[0].max()), 3),
                                                          "flexion": round(float(per_mm[1].max()), 3)},
            "joint_error_per_1deg_horn_play_at_key_deg": {"abduction": round(float(per_deg[0].max()), 3),
                                                          "flexion": round(float(per_deg[1].max()), 3)},
            "horn_transmission_min_over_region": round(float(np.abs(tn[:, inside]).min()), 3) if inside.any() else None}
        maps[s] = (inside, th, cov)
    figure(res, maps, pts, geom)
    res["figure"] = str(FIG.relative_to(ROOT))
    OUT.write_text(json.dumps(res, indent=1))
    return res


def outline(ax, inside, da=0.0, df=0.0, **kw):
    ax.contour(A_GRID + da, F_GRID + df, inside.T.astype(float), levels=[0.5], **kw)


